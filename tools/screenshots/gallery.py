"""Render the screenshots gallery (``screenshots/README.md``).

The gallery is the single MD file the root READMEs link to (per the user's
corrected requirement): one section per scenario with the image, one
English line and one Chinese line.  The Chinese texts are gallery *content*
strings coming from the scenario registry, not code comments.
"""

from __future__ import annotations

from collections.abc import Sequence
from pathlib import Path

from tools.screenshots.scenarios import Scenario

__all__ = ["render_gallery"]


def render_gallery(scenarios: Sequence[Scenario], out_dir: Path) -> Path:
    """Write ``README.md`` for *scenarios* into *out_dir*; return its path.

    Only the listed scenarios get a section.  Callers pass every scenario
    whose SVG exists in the output directory (see ``__main__.py``), so the
    gallery never references a missing image and a partial ``--only`` run
    leaves a complete gallery untouched.
    """
    lines: list[str] = [
        "# yate screenshots",
        "",
        "Generated by `python -m tools.screenshots` from the scenario registry",
        "in `tools/screenshots/scenarios.py`.  Every image is a deterministic",
        "100x30 SVG captured from the real application through Textual's pilot;",
        "the report shots (smoke / pytest / pyright / diag) are Rich re-renders",
        "of real subprocess output.",
        "",
        "> **Font note**: the SVGs embed a Fira Code `@font-face` from cdnjs.",
        "When an SVG is embedded through `<img>`, browsers do not load external",
        "resources, so the text falls back to the viewer's monospace font.",
        "Nerd Font private-use glyphs (file-type icons) render as boxes unless",
        "a Nerd Font is installed on the viewing machine.",
        "",
        "> **Report note**: the smoke / pytest / pyright / diag screenshots are",
        "samples of real runs -- durations, counts and timestamps change between",
        "regenerations.  The screensaver shot samples one animation frame, so",
        "the walker position varies per run too.",
        "",
    ]
    for scenario in scenarios:
        lines.extend(
            [
                f"### {scenario.name}",
                "",
                f'<img src="./{scenario.name}.svg" width="720">',
                "",
                scenario.desc_en,
                "",
                scenario.desc_zh,
                "",
            ]
        )
    path = out_dir / "README.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path
